-- 基线 schema:由 pg_dump --schema-only 导出后人工清理。
-- 已存在的库由 flyway.baseline-on-migrate 直接标记为已应用,本文件不会执行;
-- 空库则完全靠本文件建出来。

CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE users (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        varchar(255) NOT NULL,
    email           varchar(255) NOT NULL,
    password_hashed varchar(255) NOT NULL,
    avatar_url      varchar(255),
    bio             varchar(255),
    birthday        date,
    gender          smallint,
    phone_number    bigint,
    follower_count  integer NOT NULL DEFAULT 0,
    follow_count    integer NOT NULL DEFAULT 0,
    created_at      timestamp(6),
    updated_at      timestamp(6),
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email    UNIQUE (email),
    CONSTRAINT ck_users_gender   CHECK (gender >= 0 AND gender <= 2)
);

CREATE TABLE posts (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       bigint NOT NULL REFERENCES users(id),
    content       text NOT NULL,
    images        text,
    type          varchar(255) NOT NULL DEFAULT 'ORIGINAL',
    ref_post_id   bigint REFERENCES posts(id),
    status        smallint NOT NULL,
    visibility    smallint NOT NULL,
    deleted       boolean NOT NULL,
    is_edited     boolean DEFAULT false,
    like_count    bigint NOT NULL,
    comment_count bigint NOT NULL,
    repost_count  bigint NOT NULL DEFAULT 0,
    created_at    timestamp(6),
    updated_at    timestamp(6),
    search_vector tsvector,
    CONSTRAINT ck_posts_status     CHECK (status >= 0 AND status <= 2),
    CONSTRAINT ck_posts_visibility CHECK (visibility IN (0, 1, 2, 3)),
    CONSTRAINT ck_posts_type       CHECK (type IN ('ORIGINAL', 'REPOST', 'QUOTE'))
);

CREATE TABLE comments (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    bigint REFERENCES posts(id),
    user_id    bigint REFERENCES users(id),
    content    text NOT NULL,
    created_at timestamp(6)
);

CREATE TABLE likes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    bigint NOT NULL,
    user_id    bigint NOT NULL,
    created_at timestamp(6) NOT NULL,
    CONSTRAINT uk_likes_user_post UNIQUE (user_id, post_id)
);

CREATE TABLE follows (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id  bigint NOT NULL,
    following_id bigint NOT NULL,
    created_at   timestamp(6),
    CONSTRAINT uk_follows_follower_following UNIQUE (follower_id, following_id)
);

CREATE TABLE notifications (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       varchar(255),
    actor_id   bigint,
    target_id  bigint,
    post_id    bigint,
    content    varchar(255),
    read       boolean,
    created_at timestamp(6),
    CONSTRAINT ck_notifications_type CHECK (type IN ('LIKE', 'COMMENT', 'FOLLOW'))
);

CREATE INDEX idx_posts_user_created  ON posts   USING btree (user_id, created_at);
CREATE INDEX idx_posts_created_id    ON posts   USING btree (created_at, id);
CREATE INDEX idx_following_follower  ON follows USING btree (following_id, follower_id);
CREATE INDEX idx_post_search         ON posts   USING gin (search_vector);

CREATE FUNCTION post_search_vector_update() RETURNS trigger
    LANGUAGE plpgsql AS $$
BEGIN
  NEW.search_vector := to_tsvector('simple', coalesce(NEW.content, ''));
  RETURN NEW;
END
$$;

CREATE TRIGGER post_search_vector_trigger
    BEFORE INSERT OR UPDATE ON posts
    FOR EACH ROW EXECUTE FUNCTION post_search_vector_update();
