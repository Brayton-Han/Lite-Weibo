-- 帖子向量表与检索索引（RAG Day 5）。
--
-- 为什么单独建表而不是给 posts 加列：
--   1. 一条帖子可能切成多个 chunk（1:N）
--   2. 换 embedding 模型时新旧两套向量可以并存做对照（按 model_id 区分），不动 posts
--   3. posts 是热表，1024 维 float 列（约 4KB/行）会让 SELECT * 和全表扫明显变重
--
-- 没有对应的 JPA 实体：Hibernate 不认识 vector 类型，读写一律走 JdbcTemplate 原生 SQL。
-- 也因此 Post 上的 @Where(deleted = false) 管不到这里——软删除的帖子向量仍在表中
-- （ON DELETE CASCADE 只对物理删除生效），检索 SQL 必须 JOIN posts 并手写 deleted = false。

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE post_embeddings (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     bigint       NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    chunk_index integer      NOT NULL DEFAULT 0,
    -- 实际送进模型的文本。不总等于 posts.content（转发帖会拼上原帖），
    -- Day 6 判断「帖子改过、向量过期」也要拿它和当前内容比对
    chunk_text  text         NOT NULL,
    -- 维度必须等于 EmbeddingClient.dimensions()；换不同维度的模型要改列类型并重建索引
    embedding   vector(1024) NOT NULL,
    model_id    varchar(64)  NOT NULL,   -- EmbeddingClient.modelId()，如 voyage/voyage-4
    created_at  timestamp(6) NOT NULL DEFAULT now(),
    CONSTRAINT uk_post_embeddings_chunk UNIQUE (post_id, chunk_index, model_id)
);

-- HNSW 用余弦距离（查询必须用 <=> 才能走这个索引）。
-- Voyage 输出已单位归一化，内积（vector_ip_ops + <#>）结果相同且略快，但没选它：
-- 内积只在向量归一化时才等价于余弦，而本表要并存多个模型做对照，
-- 余弦对任何模型都正确。3000 条的规模下两者的速度差可以忽略。
--
-- m / ef_construction 取 pgvector 默认值，查询时的召回/延迟权衡用 hnsw.ef_search 调。
-- 空表上就能建（IVFFlat 才需要先有数据训练聚类中心）。
--
-- ⚠️ 多个模型的向量混在同一个索引里时，WHERE model_id = ? 是在 ANN 取出候选之后才过滤，
--    结果可能不足 k 条。届时开启 SET hnsw.iterative_scan = relaxed_order（pgvector 0.8+）。
CREATE INDEX idx_post_embeddings_hnsw
    ON post_embeddings USING hnsw (embedding vector_cosine_ops)
    WITH (m = 16, ef_construction = 64);

-- 中文词面检索（Day 10）：to_tsvector('simple') 不会给中文分词，改用 trigram 做子串相似度。
CREATE INDEX idx_posts_content_trgm
    ON posts USING gin (content gin_trgm_ops);
